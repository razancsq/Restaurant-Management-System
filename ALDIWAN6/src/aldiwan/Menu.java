    // ================== Function receipt() ==================
    public double receipt(){
        // sum all the values in the 3rd column "Amount"
        double sum = 0;
        double tax = 0.03; // to indicate 3%
        for (int i = 0; i< reciptModel.getRowCount(); i++){
            sum = sum + Double.parseDouble(reciptModel.getValueAt(i, 1).toString());
        }
        txtSubTotal.setText(Double.toString(sum));
        double cTotal1 = Double.parseDouble(txtSubTotal.getText());
        
        double cTax = (cTotal1 * tax);
        String iTaxTotal = String.format("$ %.2f", cTax);
        txtTax.setText(iTaxTotal); 
        
        double iTotal = cTotal1 + cTax;
        txtTotal.setText(String.format("$ %.2f",iTotal));
        
        // go through 3 steps to covert a double to BigDecimal then back to double
        // Convert the double to BigDecimal
        BigDecimal twoDecimal_iTotal = new BigDecimal(iTotal);
        // Set the scale to 2 decimal places with rounding
        BigDecimal formatted_iTotal = twoDecimal_iTotal.setScale(2, RoundingMode.HALF_UP);
        // Convert back to double to use it as a return value 
        iTotal = formatted_iTotal.doubleValue();
        
        return iTotal;
    }//recipt()
    
