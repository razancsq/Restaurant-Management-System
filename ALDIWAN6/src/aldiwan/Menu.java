    private void btnCashActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCashActionPerformed
        int current_person_id = SessionPerson.getCurrentPersonID();
        double totalCost=receipt();
        SessionPerson.setTableRowsCount(model.getRowCount());  // Directly from the JTable
        try{
            // DBConnection.connection ==> declared in the DBConnection CLASS
            Connection conn = (Connection) DBConnection.connection;
            String sqlInsert = "INSERT INTO orders (user_id, item_id, type, quantity, total_cost)"
                    + " VALUES (?,?,?,?,?)";
            PreparedStatement preparedStatement = conn.prepareStatement (sqlInsert);
            preparedStatement.setInt(1, current_person_id); // for customer column too
            preparedStatement.setInt(2, current_person_id);
            preparedStatement.setString(3, "Cash");
            preparedStatement.setInt(4, SessionPerson.getTableRowsCount());
            preparedStatement.setDouble(5, totalCost);
           
            // Execute the query
            int rowsAffected = preparedStatement.executeUpdate();
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this,
                    """
                    Order Saved
                    \nTotal: """+totalCost,
                    "Payment Done",
                    JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                    "Failed to save Order Information",
                    "Save Failed",
                    JOptionPane.ERROR_MESSAGE);
            }// if (rowsAffected)
            }catch(SQLException e) {
            JOptionPane.showMessageDialog(this,
                    """
                    Failed to Connect
                    \nReason:\nMenu Form\n""" + e.getMessage(),
                    "Connection Failed",
                    JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        } // try catch block
        
        // Clear the text fields
        model.setRowCount(0);
        txtSubTotal.setText("");
        txtTax.setText("");
        txtTotal.setText("");
    }//GEN-LAST:event_btnCashActionPerformed

